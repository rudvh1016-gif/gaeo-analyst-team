    """업종명 히스토그램 기준 매핑 커버리지(법인 수 가중)."""
    total = mapped = 0
    unknown = {}
    for name, n in (industry_histogram or {}).items():
        total += n
        if gaeo_sector(name):
            mapped += n
        else:
            unknown[name] = n
    return {"total": total, "mapped": mapped,
            "ratio": round(mapped / total, 4) if total else 0.0,
            "unknownIndustries": dict(sorted(unknown.items(), key=lambda kv: -kv[1]))}
